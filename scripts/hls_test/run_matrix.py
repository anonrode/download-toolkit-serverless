#!/usr/bin/env python3
"""Drive the A/B/C/D synthetic HLS matrix against the VPS origin.

This script never downloads media. It mints tokens ON the VPS (the secret never
leaves the box), drives the DEBUG app via the HlsTestDebugReceiver, and pulls
only JSONL summaries + small client state/log tails back to the PC.

Prerequisites:
  - origin running, e.g. on 127.0.0.1:8099, exposed at --public-base;
  - debug APK installed (package com.anonrode.downloader.debug);
  - adb connected; SSH key for the VPS.
  - media generated by generate_media.sh.

Examples:
  python run_matrix.py --dry-run
  python run_matrix.py --group A
  python run_matrix.py --group B --public-base http://68.155.146.145:8099/hls-test
"""
