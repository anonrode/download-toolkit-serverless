def run_cmd(cmd: list[str], *, check: bool = True, timeout: int = 120) -> subprocess.CompletedProcess:
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    if check and proc.returncode != 0:
        raise RuntimeError(f"command failed ({proc.returncode}): {' '.join(cmd)}\n{proc.stderr[:800]}")
    return proc


def ssh_cmd(args: argparse.Namespace, remote: str, timeout: int = 120) -> str:
    cmd = [
        "ssh", "-i", os.path.expanduser(args.ssh_key),
        "-o", "BatchMode=yes", "-o", "ConnectTimeout=15",
        args.ssh_host, remote,
    ]
    return run_cmd(cmd, timeout=timeout).stdout


def adb_cmd(args: argparse.Namespace, *parts: str, timeout: int = 60) -> str:
    cmd = ["adb"]
    if args.serial:
        cmd += ["-s", args.serial]
    cmd += list(parts)
    return run_cmd(cmd, timeout=timeout).stdout


def adb_shell(args: argparse.Namespace, *parts: str, timeout: int = 60) -> str:
    return adb_cmd(args, "shell", *parts, timeout=timeout)


def broadcast(args: argparse.Namespace, action: str, receiver: str, extras: list[str]) -> None:
    adb_shell(
        args, "am", "broadcast",
        "-a", action,
        "-n", f"{args.package}/{args.package}.{receiver}",
        *extras,
    )


def mint(args: argparse.Namespace, run: dict[str, Any], task: int) -> dict[str, Any]:
    remote = (
        f"python3 {shlex.quote(args.remote_dir + '/mint_token.py')} "
        f"--run {shlex.quote(run['id'])} --task {task} --lanes {run['lanes']} "
        f"--ttl {run['ttl']} --quota-mb {run.get('quota_mb', 0)} "
        f"--after-mb {run.get('after_mb', 0)} --rate-kib {run.get('rate_kib', 0)} "
        f"--secret-file {shlex.quote(args.remote_dir + '/secret')} "
        f"--url-base {shlex.quote(args.public_base)} --json"
    )
    out = ssh_cmd(args, remote).strip().splitlines()
    if not out:
        raise RuntimeError("mint_token returned no output")
    return json.loads(out[-1])


def reset_run(args: argparse.Namespace, run_id: str) -> None:
    url = f"{args.origin_url.rstrip('/')}/admin/reset?run={run_id}"
    ssh_cmd(args, f"curl -sS -X POST {shlex.quote(url)}")


def fetch_summary(args: argparse.Namespace, run_id: str) -> dict[str, Any]:
    url = f"{args.origin_url.rstrip('/')}/admin/summary?run={run_id}"
    out = ssh_cmd(args, f"curl -sS {shlex.quote(url)}").strip()
    return json.loads(out) if out else {}


def fetch_requests_jsonl(args: argparse.Namespace, run_id: str) -> str:
    path = f"{args.remote_dir}/runs/{run_id}/requests.jsonl"
    return ssh_cmd(args, f"cat {shlex.quote(path)} 2>/dev/null || true", timeout=120)


def fetch_client_state(args: argparse.Namespace) -> str:
    try:
        return adb_cmd(args, "exec-out", "run-as", args.package, "cat", "files/hls-test-state.txt")
    except Exception:
        return ""


def fetch_client_log_tail(args: argparse.Namespace, max_chars: int = 300_000) -> str:
    try:
        names = adb_shell(args, "run-as", args.package, "ls", "files/logs").split()
        if not names:
            return ""
        newest = sorted(names)[-1]
        text = adb_cmd(args, "exec-out", "run-as", args.package, "cat", f"files/logs/{newest}")
        return text[-max_chars:]
    except Exception:
        return ""


def state_is_terminal(state_text: str, run_id: str, expected_tasks: int) -> bool:
    rows = []
    for ln in state_text.splitlines():
        parts = ln.split("|")
        if len(parts) >= 8 and parts[7].startswith(run_id + "-task"):
            rows.append(parts)
    if len(rows) < expected_tasks:
        return False
    terminal = sum(1 for parts in rows if parts[1] in ("COMPLETED", "FAILED"))
    return terminal >= expected_tasks


def execute_run(args: argparse.Namespace, run: dict[str, Any]) -> None:
    run_id = run["id"]
    out_dir = Path(args.out) / run_id
    out_dir.mkdir(parents=True, exist_ok=True)
    print(f"[matrix] {run_id}: tasks={run['tasks']} lanes={run['lanes']} ttl={run['ttl']}m "
          f"rate={run.get('rate_kib', 0)}KiB/s quota={run.get('quota_mb', 0)}MB "
          f"after={run.get('after_mb', 0)}MB start_expiry={run.get('start_expiry', False)}")

    reset_run(args, run_id)
    adb_shell(args, "am", "force-stop", args.package)
    adb_shell(args, "monkey", "-p", args.package, "1")
    time.sleep(args.launch_wait)
    broadcast(args, f"{args.package}.HLS_TEST", "HlsTestDebugReceiver", [
        "--es", "op", "settings",
        "--ei", "max_tasks", str(run["tasks"]),
        "--ei", "lanes", str(run["lanes"]),
    ])

    tokens = [mint(args, run, i + 1) for i in range(run["tasks"])]
    if run.get("start_expiry"):
        wait = int(run["ttl"] * 60) + args.expiry_margin
        print(f"[matrix] {run_id}: waiting {wait}s for token expiry before launch")
        time.sleep(wait)

    for i, token in enumerate(tokens, start=1):
        broadcast(args, f"{args.package}.HLS_TEST", "HlsTestDebugReceiver", [
            "--es", "op", "enqueue",
            "--es", "url", token["url"],
            "--es", "title", f"{run_id}-task{i}",
            "--ei", "task", str(i),
            "--ei", "lanes", str(run["lanes"]),
        ])
        time.sleep(0.5)

    started = time.time()
    summary: dict[str, Any] = {}
    state_text = ""
    while time.time() - started < args.timeout:
        time.sleep(args.poll)
        try:
            summary = fetch_summary(args, run_id)
        except Exception as exc:
            print(f"[matrix] {run_id}: summary poll failed: {exc}")
            continue
        state_text = fetch_client_state(args)
        (out_dir / "client-state.txt").write_text(state_text, encoding="utf-8")
        if state_is_terminal(state_text, run_id, run["tasks"]):
            print(f"[matrix] {run_id}: client terminal after {int(time.time() - started)}s")
            break

    log_tail = fetch_client_log_tail(args)
    (out_dir / "client-log-tail.txt").write_text(log_tail, encoding="utf-8")
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2, sort_keys=True), encoding="utf-8")
    (out_dir / "requests.jsonl").write_text(fetch_requests_jsonl(args, run_id), encoding="utf-8")
    (out_dir / "params.json").write_text(json.dumps(run, indent=2, sort_keys=True), encoding="utf-8")
    adb_shell(args, "am", "force-stop", args.package)
    print(f"[matrix] {run_id}: requests={summary.get('requests', 0)} "
          f"status={summary.get('status_counts', {})} reasons={summary.get('reasons', {})}")


def main() -> int:
    ap = argparse.ArgumentParser(description="Run the synthetic HLS A/B/C/D matrix.")
    ap.add_argument("--group", choices=["A", "B", "C", "D", "all"], default="all")
    ap.add_argument("--run", action="append", default=[], help="specific run id(s)")
    ap.add_argument("--ssh-host", default=os.environ.get("ANON_VPS_HOST", "Anon@68.155.146.145"))
    ap.add_argument("--ssh-key", default=os.environ.get("ANON_VPS_KEY", "~/.ssh/anon_vps"))
    ap.add_argument("--remote-dir", default="/home/Anon/hls-test-origin")
    ap.add_argument("--origin-url", default="http://127.0.0.1:8099/hls-test",
                    help="admin URL reachable FROM the VPS")
    ap.add_argument("--public-base", default="http://68.155.146.145:8099/hls-test")
    ap.add_argument("--package", default="com.anonrode.downloader.debug")
    ap.add_argument("--serial", default=None, help="adb -s serial")
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[2] / "scratch" / "hls_matrix"))
    ap.add_argument("--timeout", type=int, default=1800)
    ap.add_argument("--poll", type=float, default=5.0)
    ap.add_argument("--launch-wait", type=float, default=4.0)
    ap.add_argument("--expiry-margin", type=int, default=15)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    selected = [r for r in RUNS
                if (args.group == "all" or r["group"] == args.group)
                and (not args.run or r["id"] in args.run)]
    if not selected:
        print("no runs selected", file=sys.stderr)
        return 2
    if args.dry_run:
        for r in selected:
            print(f"{r['id']}: tasks={r['tasks']} lanes={r['lanes']} ttl={r['ttl']} "
                  f"rate={r.get('rate_kib', 0)} quota={r.get('quota_mb', 0)} "
                  f"after={r.get('after_mb', 0)} start_expiry={r.get('start_expiry', False)}")
        print(f"would write to {Path(args.out).resolve()}")
        return 0

    Path(args.out).mkdir(parents=True, exist_ok=True)
    for r in selected:
        execute_run(args, r)
    return 0


if __name__ == "__main__":
    sys.exit(main())
